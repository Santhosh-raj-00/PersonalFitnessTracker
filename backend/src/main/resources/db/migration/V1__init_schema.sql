-- FitTrack Baseline Schema Migration (V1)
-- Compatible with PostgreSQL and H2

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    age INT,
    height_cm DOUBLE PRECISION,
    weight_kg DOUBLE PRECISION,
    fitness_goal VARCHAR(50),
    experience_level VARCHAR(50),
    available_equipment VARCHAR(255),
    daily_calorie_target INT,
    daily_protein_target_grams INT,
    CONSTRAINT fk_profile_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    primary_muscle VARCHAR(50) NOT NULL,
    secondary_muscles VARCHAR(255),
    equipment VARCHAR(50) NOT NULL,
    difficulty VARCHAR(50) NOT NULL,
    form_tips VARCHAR(2000),
    demo_image_url VARCHAR(500),
    is_custom BOOLEAN DEFAULT FALSE,
    created_by_id BIGINT,
    CONSTRAINT fk_exercise_creator FOREIGN KEY (created_by_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS routines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(1000),
    is_template BOOLEAN DEFAULT FALSE,
    split_type VARCHAR(50),
    created_at TIMESTAMP,
    CONSTRAINT fk_routine_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS routine_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routine_id BIGINT NOT NULL,
    day_name VARCHAR(255) NOT NULL,
    day_order INT NOT NULL,
    CONSTRAINT fk_routine_days FOREIGN KEY (routine_id) REFERENCES routines(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS routine_exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routine_day_id BIGINT NOT NULL,
    exercise_id BIGINT NOT NULL,
    exercise_order INT NOT NULL,
    target_sets INT NOT NULL,
    target_rep_range VARCHAR(50) NOT NULL,
    rest_seconds INT NOT NULL,
    notes VARCHAR(500),
    CONSTRAINT fk_routine_day_ex FOREIGN KEY (routine_day_id) REFERENCES routine_days(id) ON DELETE CASCADE,
    CONSTRAINT fk_routine_exercise FOREIGN KEY (exercise_id) REFERENCES exercises(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS workout_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    routine_day_id BIGINT,
    session_name VARCHAR(255) NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP,
    notes VARCHAR(1000),
    total_volume_kg DOUBLE PRECISION DEFAULT 0,
    status VARCHAR(50) NOT NULL,
    CONSTRAINT fk_session_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_session_routine_day FOREIGN KEY (routine_day_id) REFERENCES routine_days(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS workout_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    exercise_id BIGINT NOT NULL,
    set_order INT NOT NULL,
    weight_kg DOUBLE PRECISION NOT NULL,
    reps INT NOT NULL,
    rpe DOUBLE PRECISION,
    is_warmup BOOLEAN DEFAULT FALSE,
    estimated_1rm DOUBLE PRECISION,
    is_pr BOOLEAN DEFAULT FALSE,
    logged_at TIMESTAMP,
    CONSTRAINT fk_set_session FOREIGN KEY (session_id) REFERENCES workout_sessions(id) ON DELETE CASCADE,
    CONSTRAINT fk_set_exercise FOREIGN KEY (exercise_id) REFERENCES exercises(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS personal_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    exercise_id BIGINT NOT NULL,
    record_type VARCHAR(50) NOT NULL,
    record_value DOUBLE PRECISION NOT NULL,
    reps INT,
    achieved_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_pr_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_pr_exercise FOREIGN KEY (exercise_id) REFERENCES exercises(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS body_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    recorded_date DATE NOT NULL,
    weight_kg DOUBLE PRECISION,
    body_fat_percentage DOUBLE PRECISION,
    chest_cm DOUBLE PRECISION,
    waist_cm DOUBLE PRECISION,
    arms_cm DOUBLE PRECISION,
    thighs_cm DOUBLE PRECISION,
    notes VARCHAR(500),
    CONSTRAINT fk_metric_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS progress_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    recorded_date DATE NOT NULL,
    photo_url VARCHAR(500) NOT NULL,
    tag VARCHAR(50),
    CONSTRAINT fk_photo_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
